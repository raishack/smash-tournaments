import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import express from 'express';
import { DisplayAdminStore } from '../backend/dist/modules/display-admin/display-admin.store.js';
import { createDisplayAdminRouter } from '../backend/dist/modules/display-admin/display-admin.routes.js';
import { displayFixture } from '../backend/tests/fixtures/display-fixtures.mjs';
const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_PATH || 'playwright');
const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'gt-display-ui-'));
const output = path.resolve('build/display-review');
await fs.mkdir(output, { recursive: true });
const store = new DisplayAdminStore(directory); await store.ensureReady();
await store.saveBracketRenderMode('modern');
await store.saveTheme({ id: 'test-theme', key: 'test', name: 'Theme de prueba', matchers: ['demo'], cssVars: { '--custom-var': 'kept' }, assets: {} });
const fixture = displayFixture(32);
const app = express(); app.use(express.json());
let writes = 0;
app.use('/api/display-admin', (req, res, next) => { if (req.method === 'POST') writes++; next(); }, createDisplayAdminRouter(store));
app.get('/api/tournaments', (req, res) => res.json([fixture.tournament]));
app.get('/api/tournaments/:id', (req, res) => res.json(fixture));
app.get('/config.js', (req, res) => res.type('js').send(`window.GTDisplayConfig = { backendUrl: location.origin, appClientKey: 'test', pollIntervalMs: 300, requestTimeoutMs: 500, sponsorMax: 0, themeManifestUrl: '/themes/themes.json', idleImageUrl:'/idle-placeholder.svg' };`));
app.use(express.static(path.resolve('display-web')));
const server = app.listen(0, '127.0.0.1'); await new Promise(resolve => server.once('listening', resolve));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH, headless: true });
const errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  page.on('pageerror', error => errors.push(error.message));
  await store.accounts.createUser('display-test','display-test-password');
  const token = await store.verifyLogin('display-test', 'display-test-password');
  await page.addInitScript(token => localStorage.setItem('gt_display_admin_token', token), token);
  await page.goto(`${base}/admin/`);
  await page.locator('#display-settings-form').waitFor();
  assert.equal(await page.locator('[data-admin-section]:visible').count(), 1);
  await page.locator('#load-preview').click();
  const preview = page.frameLocator('#display-preview-frame iframe');
  await preview.locator('.modern-match-card').first().waitFor();
  await page.locator('[data-preset="dense"]').click();
  await preview.locator('html[data-density="compact"]').waitFor();
  assert.equal(writes, 0, 'Unsaved preview must not change the server');
  assert.equal((await store.readState()).displaySettings.bracketDensity, 'balanced');
  const denseCount = await preview.locator('.modern-match-card').count();
  console.log('Dense Full HD matches on first page:', denseCount);
  assert(denseCount >= 10);
  await page.waitForFunction(() => { const v = document.querySelector('iframe').contentDocument.querySelector('.bracket-viewport'); return v && v.scrollHeight <= v.clientHeight + 4; });
  await page.locator('#display-settings-form [name="showCharacters"]').uncheck();
  await preview.locator('.modern-entrant-character-icon').first().waitFor({ state: 'detached' });
  await page.locator('#display-settings-form [name="showCharacters"]').check();
  await preview.locator('.modern-entrant-character-icon').first().waitFor();
  await page.locator('#display-settings-form [name="bracketLayout"]').selectOption('combined');
  await page.waitForFunction(() => document.querySelector('iframe').contentDocument.querySelectorAll('.modern-bracket-cluster').length === 2);
  await page.locator('#display-settings-form [name="bracketLayout"]').selectOption('separate');
  await page.waitForFunction(() => document.querySelector('iframe').contentDocument.querySelectorAll('.modern-bracket-cluster').length === 1);
  await page.locator('#next-preview').click();
  await page.waitForFunction(() => document.querySelector('iframe').contentDocument.querySelector('.scene-title .eyebrow').textContent.includes('2/'));
  await page.locator('[data-preset="dense"]').click();
  await page.locator('#preview-resolution').selectOption('3840,2160');
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.innerWidth === 3840);
  await page.locator('#preview-resolution').selectOption('1080,1920');
  await page.waitForFunction(() => document.querySelector('iframe').contentWindow.innerHeight === 1920);
  await page.locator('#preview-resolution').selectOption('1920,1080');
  await page.waitForFunction(() => document.querySelector('iframe').contentDocument.querySelectorAll('.modern-bracket-cluster').length === 1);
  await page.screenshot({ path: path.join(output, 'admin-display-desktop.png'), animations: 'disabled', fullPage: true });
  await page.locator('#display-settings-form [type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('[data-settings-status]').textContent === 'Saved');
  assert.equal((await store.readState()).displaySettings.bracketDensity, 'compact');

  // A draft in one section must survive saving a different form and refetching state.
  await page.locator('#display-settings-form [name="textScale"]').fill('115');
  await page.locator('[data-nav="messages"]').click();
  await page.locator('[name="msg_telegramLadderCompleted"]').fill('Ladder de {{tournament_title}}');
  assert.match(await page.locator('#message-example-text').textContent(), /Community Weekly/);
  await page.locator('#message-channel').selectOption('whatsapp');
  assert.equal(await page.locator('[data-message-channel="telegram"]:visible').count(), 0);
  await page.locator('[name="msg_whatsappLadderCompletedCaption"]').fill('Ladder WA de {{tournament_title}}');
  await page.locator('[data-nav="themes"]').click();
  await page.locator('[data-theme-id="test-theme"]').click();
  await page.locator('#theme-form [name="name"]').fill('Theme actualizado');
  await page.locator('#theme-form [name="raw_--accent"]').fill('#ffaa00');
  assert.match(await page.locator('#theme-preview-live').innerHTML(), /#ffaa00/);
  await page.locator('#theme-form [type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('#theme-form [data-form-status]').textContent === 'No pending changes');
  assert.equal((await store.readState()).themes.find(t => t.id === 'test-theme').cssVars['--custom-var'], 'kept');
  await page.locator('[data-nav="display"]').click();
  assert.equal(await page.locator('[name="textScale"]').inputValue(), '115');
  assert.match(await page.locator('#display-settings-form [data-form-status]').textContent(), /Unsaved changes/);
  await page.locator('[data-nav="messages"]').click();
  assert.equal(await page.locator('[name="msg_telegramLadderCompleted"]').inputValue(), 'Ladder de {{tournament_title}}');
  await page.locator('#messages-form [type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('#messages-form [data-form-status]').textContent === 'No pending changes');
  assert.equal((await store.readState()).messageTemplates.whatsappLadderCompletedCaption, 'Ladder WA de {{tournament_title}}');
  await page.locator('[data-nav="themes"]').click();
  await page.locator('#duplicate-theme-btn').click();
  assert.equal(await page.locator('#theme-form [name="id"]').inputValue(), '');
  assert.match(await page.locator('#theme-form [name="name"]').inputValue(), /copy/);
  await page.locator('#theme-form [type="submit"]').click();
  await page.waitForFunction(() => document.querySelector('#theme-form [name="id"]').value !== '');
  page.once('dialog', dialog => dialog.accept());
  await page.locator('#delete-theme-btn').click();
  await page.waitForFunction(() => ![...document.querySelectorAll('[data-theme-id]')].some(e => e.textContent.includes('copy')));
  assert(await page.locator('[data-theme-id="theme_base"]').count());

  await page.locator('[data-nav="display"]').click();
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Admin must fit mobile width');
  await page.screenshot({ path: path.join(output, 'admin-mobile.png'), animations: 'disabled', fullPage: true });
  for (const section of ['messages', 'media', 'themes', 'access']) {
    await page.locator(`[data-nav="${section}"]`).click();
    if (await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)) {
      console.log('Mobile overflow', section, await page.evaluate(() => [...document.querySelectorAll('body *')].filter(e => e.getBoundingClientRect().right > innerWidth + 1).map(e => [e.tagName, e.className, e.getBoundingClientRect().width]).slice(-20)));
      await page.screenshot({ path: path.join(output, `admin-${section}-overflow.png`), fullPage: true });
    }
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, `${section} must fit mobile width`);
  }

  // Overview retains every match of the shown bracket and remains sharp at native 4K.
  const display = await browser.newPage({ viewport: { width: 1920, height: 1080 } });
  display.on('pageerror', error => errors.push(error.message));
  await display.goto(base);
  await display.locator('.modern-match-card').first().waitFor();
  await display.waitForFunction(() => { const v = document.querySelector('.bracket-viewport'); return v && v.scrollHeight <= v.clientHeight + 4; });
  await display.screenshot({ path: path.join(output, 'display-compact-1080p.png'), animations: 'disabled' });
  await display.setViewportSize({ width: 3840, height: 2160 });
  await display.waitForFunction(() => parseFloat(getComputedStyle(document.querySelector('.modern-entrant-name')).fontSize) >= 32);
  await display.screenshot({ path: path.join(output, 'display-compact-4k.png'), animations: 'disabled' });
  await display.setViewportSize({ width: 1080, height: 1920 });
  await display.waitForFunction(() => { const v = document.querySelector('.bracket-viewport'); return v && v.scrollHeight <= v.clientHeight + 4 && v.scrollWidth <= v.clientWidth + 4; });
  await display.screenshot({ path: path.join(output, 'display-portrait.png'), animations: 'disabled' });
  await display.setViewportSize({ width: 1920, height: 1080 });
  await display.locator('.screen-controls summary').click();
  await display.locator('[data-field="bracketViewport"]').selectOption('overview');
  await display.waitForFunction(() => document.querySelectorAll('.modern-match-card').length === 31);
  await display.waitForFunction(() => { const v = document.querySelector('.bracket-viewport'); return v && v.scrollHeight <= v.clientHeight + 4; });
  await display.locator('.screen-controls summary').click();
  await display.screenshot({ path: path.join(output, 'display-overview.png'), animations: 'disabled' });
  await display.locator('.screen-controls summary').click();
  await display.locator('[data-field="bracketLayout"]').selectOption('combined');
  await display.waitForFunction(() => document.querySelectorAll('.modern-match-card').length === 46);
  await display.locator('[data-reset]').click();
  assert.equal(await display.locator('[data-field="bracketViewport"]').inputValue(), 'focus');
  assert.equal(await display.locator('[data-field="bracketLayout"]').inputValue(), 'separate');
  assert.equal(await display.locator('[data-field="bracketDensity"]').inputValue(), 'compact');
  assert.deepEqual(errors, []);
  console.log('PASS: real admin routes, live unsaved preview, presets, resolutions, saves, drafts, messages, theme duplication/deletion, mobile sections, overview and local reset');
} finally {
  await browser.close();
  await new Promise(resolve => server.close(resolve));
  await fs.rm(directory, { recursive: true, force: true });
}
