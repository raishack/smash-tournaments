// Real web interfaces with synthetic tournament data. Never connects to production.
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import express from 'express';
import { chromium } from 'playwright';
import { fortniteFixture } from '../backend/tests/fixtures/fortnite-fixture.mjs';
import { displayFixture } from '../backend/tests/fixtures/display-fixtures.mjs';
import { DisplayAdminStore } from '../backend/dist/modules/display-admin/display-admin.store.js';
import { createDisplayAdminRouter } from '../backend/dist/modules/display-admin/display-admin.routes.js';
import { createManageRouter } from '../backend/dist/modules/manage/manage.routes.js';
import { createFortniteRouters } from '../backend/dist/modules/fortnite/fortnite.routes.js';

const cleanup = [], temp = await fs.mkdtemp(path.join(os.tmpdir(), 'smash-tournaments-examples-'));
const output = path.resolve('docs/en/images'); await fs.mkdir(output, {recursive:true});
const f = await fortniteFixture({after:fn=>cleanup.push(fn)}, {count:15,size:10,games:3});
const names = ['Nova','Ember','Orbit','Luna','Blaze','Echo','Pixel','Comet','Atlas','Sora','Cinder','Vega','Flux','Kite','Aero','Zen'];
await f.repo.replaceParticipants(f.tournament.id, f.participants.map((p,i)=>({...p,displayName:names[i]})));
await f.repo.saveTournament({...f.tournament,title:'Community Battle Royale',settings:{...f.tournament.settings,displayEnabled:true}});
const fixture = displayFixture(16, 'community-cup');
fixture.tournament.title = 'Smash Tournaments · Community Cup';
fixture.tournament.gameTitle = 'Community Singles';
delete fixture.tournament.importSource;
fixture.tournament.settings.displayEnabled = true;
fixture.participants.forEach((p,i)=>{p.displayName=names[i];});
fixture.matches.forEach(m=>{delete m.externalRef; m.characterSelections=[]; m.participants.forEach(p=>{const found=fixture.participants.find(x=>x.id===p.participantId); if(found)p.displayName=found.displayName;});});
fixture.matches[0].status='PLAYING'; fixture.matches[0].setupNumber=1;
const now=new Date().toISOString();
await f.repo.saveTournament({...f.tournament,...fixture.tournament,createdAt:now,updatedAt:now,settings:{...f.tournament.settings,...fixture.tournament.settings,bracketMode:'STANDARD'}});
await f.repo.replaceParticipants(fixture.tournament.id,fixture.participants.map(p=>({...p,tournamentId:fixture.tournament.id,status:'ACTIVE',checkedIn:true,createdAt:now})));
await f.repo.replaceMatches(fixture.tournament.id,fixture.matches.map(m=>({...m,createdAt:now,updatedAt:now})));
const store=new DisplayAdminStore(temp); await store.ensureReady(); await store.saveBracketRenderMode('modern');
await store.accounts.createUser('demo-admin','example-only-password');
const token=await store.verifyLogin('demo-admin','example-only-password');
const app=express(); app.use(express.json());
app.use('/api/display-admin',createDisplayAdminRouter(store));
app.use('/api/manage',createManageRouter(f.tournaments,undefined,store));
const fortnite=createFortniteRouters(f.service,'https://your-domain.example');
app.use('/api/fortnite',fortnite.publicRouter);
// Fixture server is loopback-only and disposable; it contains no real accounts.
app.use('/api/tournaments/:tournamentId/fortnite',fortnite.protectedRouter);
app.get('/api/tournaments',(_req,res)=>res.json([fixture.tournament]));
app.get('/api/tournaments/:id',(_req,res)=>res.json(fixture));
app.get('/api/public-registration/:id',(_req,res)=>res.json({title:'Community Teams Cup',gameTitle:'Valorant',platform:'PC',startsAt:'2027-04-17T14:00:00Z',maxParticipants:16,availablePlaces:10,open:true,canOpen:true,teamSize:5,reserveCount:2,allowSoloRegistration:true,waitlistEnabled:true}));
app.post('/api/top8/session',(_req,res)=>res.json({tournamentId:'community-top',title:'Community Cup',gameTitle:'Community Singles',game:'custom',date:'2027-04-17T14:00:00Z',participantCount:32,topCount:8,warnings:[],catalog:{smash:[],rivals:[],custom:[]},players:names.slice(0,8).map((name,i)=>({id:'top-'+i,name,placement:[1,2,3,4,5,5,7,7][i],characters:[],roster:[]}))}));
app.get('/config.js',(_req,res)=>res.type('js').send(`window.GTDisplayConfig={backendUrl:location.origin,appClientKey:'example-only',pollIntervalMs:60000,requestTimeoutMs:5000,sponsorMax:0,themeManifestUrl:'/themes/themes.json',idleImageUrl:'/idle-placeholder.svg'};`));
app.use(express.static(path.resolve('display-web')));
const server=app.listen(0,'127.0.0.1'); await new Promise(r=>server.once('listening',r));
const base='http://127.0.0.1:'+server.address().port;
const browser=await chromium.launch({headless:true,...(process.env.CHROME_PATH?{executablePath:process.env.CHROME_PATH}:{})});
const errors=[];
try {
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  page.on('pageerror',e=>errors.push(e.message));
  page.on('dialog',dialog=>dialog.accept());
  await page.addInitScript(token=>{localStorage.setItem('gt_display_admin_token',token);localStorage.setItem('gt_manage_admin_token',token);},token);
  await page.goto(base); await page.locator('.modern-match-card').first().waitFor();
  await page.locator('.screen-controls summary').click();
  await page.locator('[data-field="bracketViewport"]').selectOption('overview');
  await page.waitForFunction(()=>document.querySelectorAll('.modern-match-card').length===15);
  await page.locator('.screen-controls summary').click();
  await page.screenshot({path:path.join(output,'display-bracket.png'),animations:'disabled'});
  await page.goto(base+'/admin/'); await page.locator('#display-settings-form').waitFor();
  await page.locator('#load-preview').click(); await page.frameLocator('#display-preview-frame iframe').locator('.modern-match-card').first().waitFor();
  await page.screenshot({path:path.join(output,'display-admin.png'),animations:'disabled'});
  await page.setViewportSize({width:1440,height:1000});
  await page.goto(base+'/manage/'); await page.getByText('Community Cup',{exact:false}).first().waitFor();
  await page.screenshot({path:path.join(output,'manage.png'),animations:'disabled'});
  await page.goto(base+'/register/?tournamentId=community-teams'); await page.locator('#registration').waitFor();
  await page.screenshot({path:path.join(output,'registration.png'),animations:'disabled',fullPage:true});
  await page.goto(base+'/top8/?tournamentId=community-top#session='+'a'.repeat(64)); await page.locator('#editor').waitFor();
  await page.locator('#logo-file').setInputFiles(path.resolve('display-web/brand-logo.png'));
  await page.waitForFunction(()=>document.querySelector('canvas')?.width>0);
  await page.screenshot({path:path.join(output,'top8-editor.png'),animations:'disabled'});
  const ticket=await(await fetch(base+`/api/tournaments/${f.tournament.id}/fortnite/session`,{method:'POST'})).json();
  await page.goto(base+'/fortnite/?tournamentId='+f.tournament.id+new URL(ticket.url).hash);
  await page.locator('#generate').click(); await page.locator('.score-row').first().waitFor();
  await page.locator('#vip').fill('Guest VIP');
  await page.screenshot({path:path.join(output,'fortnite.png'),animations:'disabled'});
  assert.deepEqual(errors,[], 'Examples must have no browser script errors');
  console.log('Captured six example screens with synthetic data in docs/en/images.');
} finally {
  await browser.close(); await new Promise(r=>server.close(r));
  for(const fn of cleanup) await fn();
  await fs.rm(temp,{recursive:true,force:true});
}
